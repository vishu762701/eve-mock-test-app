#!/usr/bin/env python3
"""
tools/extract_tg_constants.py
Extracts constants directly from official Telegram Android source files and
populates docs/parity/manifest.json and designsystem/TelegramParity.kt.
"""

import argparse
import json
import os
import re
import sys
from pathlib import Path

DEFAULT_SOURCE_ROOTS = [
    Path(os.path.expanduser("~/tg-src/Telegram-master/TMessagesProj/src/main/java")),
    Path(os.path.expanduser("/data/data/com.termux/files/home/tg-src/Telegram-master/TMessagesProj/src/main/java")),
]

def find_source_file(source_root: Path, rel_path: str) -> Path:
    # Check directly
    p1 = source_root / rel_path
    if p1.is_file():
        return p1
    # Check with TMessagesProj/src/main/java stripped or added
    alt_roots = [
        source_root,
        source_root.parent,
        source_root.parent.parent,
        source_root.parent.parent.parent,
    ]
    for r in alt_roots:
        cand = r / rel_path
        if cand.is_file():
            return cand
        cand2 = r / "TMessagesProj" / "src" / "main" / "java" / rel_path
        if cand2.is_file():
            return cand2
    return p1

def parse_val_from_snippet(snippet: str, kind: str, custom_pattern: str = None):
    if custom_pattern:
        m = re.search(custom_pattern, snippet)
        if m:
            v = float(m.group(1))
            return int(v) if v.is_integer() else v

    if kind in ("dp", "sp"):
        # Match dp(123), dpf2(123), etc.
        m = re.search(r'dp(?:f2)?\(([\d.]+)', snippet)
        if m:
            v = float(m.group(1))
            return int(v) if v.is_integer() else v
        m = re.search(r'=\s*([\d.]+)', snippet)
        if m:
            v = float(m.group(1))
            return int(v) if v.is_integer() else v
    elif kind == "ms":
        # Match setDuration(123) or = 123
        m = re.search(r'setDuration\(([\d]+)', snippet)
        if m:
            return int(m.group(1))
        m = re.search(r'openDuration\s*=\s*([\d]+)', snippet)
        if m:
            return int(m.group(1))
        m = re.search(r'=\s*([\d]+)', snippet)
        if m:
            return int(m.group(1))
    elif kind == "alpha":
        # e.g. dimBehindAlpha = 51 -> 51 / 255 = 0.2
        m = re.search(r'dimBehindAlpha\s*=\s*([\d]+)', snippet)
        if m:
            return round(int(m.group(1)) / 255.0, 3)
        m = re.search(r'([\d.]+f?)', snippet)
        if m:
            return float(m.group(1).rstrip('f'))
    elif kind == "ratio":
        m = re.search(r'([\d.]+)', snippet)
        if m:
            v = float(m.group(1))
            return int(v) if v.is_integer() else v
    return None

def process_manifest(manifest_path: Path, source_root: Path, write_code: bool = True):
    if not manifest_path.exists():
        print(f"Manifest not found: {manifest_path}", file=sys.stderr)
        return False

    with open(manifest_path, "r", encoding="utf-8") as f:
        data = json.load(f)

    updated = []
    for entry in data:
        file_rel = entry["telegram_file"]
        line_no = entry["telegram_line"]
        src_file = find_source_file(source_root, file_rel)
        if not src_file.is_file():
            print(f"Warning: could not find {file_rel} at {src_file}", file=sys.stderr)
            updated.append(entry)
            continue

        with open(src_file, "r", encoding="utf-8", errors="replace") as sf:
            lines = sf.readlines()

        if 1 <= line_no <= len(lines):
            snippet = lines[line_no - 1].strip()
            entry["telegram_snippet"] = snippet
            val = parse_val_from_snippet(snippet, entry.get("kind", ""), entry.get("pattern"))
            if val is not None:
                entry["value"] = val
        else:
            print(f"Line {line_no} out of bounds for {file_rel} (len {len(lines)})", file=sys.stderr)

        updated.append(entry)

    with open(manifest_path, "w", encoding="utf-8") as f:
        json.dump(updated, f, indent=2)
        f.write("\n")

    print(f"Updated {len(updated)} entries in {manifest_path}")

    if write_code:
        generate_kotlin_parity(updated)

    return True

def generate_kotlin_parity(entries):
    code_path = Path("app/src/main/java/com/eve/app/designsystem/TelegramParity.kt")
    code_path.parent.mkdir(parents=True, exist_ok=True)

    lines = [
        "/*",
        " * Auto-generated by tools/extract_tg_constants.py. Do not edit manually.",
        " * Single source of truth for Telegram-derived parity constants.",
        " */",
        "",
        "package com.eve.app.designsystem",
        "",
        "object TelegramParity {",
    ]

    for e in sorted(entries, key=lambda x: x["eve_symbol"]):
        sym = e["eve_symbol"]
        val = e["value"]
        kind = e.get("kind", "")
        file = e.get("telegram_file", "")
        line = e.get("telegram_line", "")
        snippet = e.get("telegram_snippet", "")

        lines.append(f"    // Telegram: {file}:{line} -> `{snippet}`")
        if isinstance(val, bool):
            lines.append(f"    const val {sym}: Boolean = {str(val).lower()}")
        elif isinstance(val, int):
            if kind == "ms":
                lines.append(f"    const val {sym}: Long = {val}L")
            else:
                lines.append(f"    const val {sym}: Int = {val}")
        elif isinstance(val, float):
            lines.append(f"    const val {sym}: Float = {val}f")
        else:
            lines.append(f"    const val {sym}: String = \"{val}\"")
        lines.append("")

    lines.append("}")
    lines.append("")

    code_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"Generated {code_path}")

def main():
    parser = argparse.ArgumentParser(description="Extract Telegram constants into manifest and code")
    parser.add_argument("--source", type=Path, default=None, help="Path to Telegram source root")
    parser.add_argument("--manifest", type=Path, default=Path("docs/parity/manifest.json"))
    args = parser.parse_args()

    source_root = args.source
    if not source_root:
        for cand in DEFAULT_SOURCE_ROOTS:
            if cand.exists():
                source_root = cand
                break

    if not source_root or not source_root.exists():
        print("ERROR: Telegram source directory not found. Please extract Telegrammaster.zip to ~/tg-src/", file=sys.stderr)
        sys.exit(1)

    process_manifest(args.manifest, source_root)

if __name__ == "__main__":
    main()
